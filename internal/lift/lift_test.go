const head = `version: 0.5
go_module: example.com/x
tiers: [a]
modules:
  core: { tier: a }
`

func write(t *testing.T, root, rel, src string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
}

// project는 코드 루트와 설계 디렉토리를 만든다. design은 head 뒤에 붙는다.
func project(t *testing.T, design string, code map[string]string) (string, string) {
	t.Helper()
	root := t.TempDir()
	write(t, root, "go.mod", "module example.com/x\n\ngo 1.22\n")
	write(t, root, "design/d.yaml", head+design)
	for rel, src := range code {
		write(t, root, rel, src)
	}
	return filepath.Join(root, "design"), root
}

func draft(t *testing.T, design string, code map[string]string) *Result {
	t.Helper()
	dir, root := project(t, design, code)
	r, err := Draft(dir, root)
	if err != nil {
		t.Fatal(err)
	}
	return r
}

func lines(r *Result) string {
	var out []string
	for _, n := range r.Nodes {
		out = append(out, n.Kind+" "+n.Line)
	}
	return strings.Join(out, "\n")
}

func TestErrorsAndConsts(t *testing.T) {
	r := draft(t, "", map[string]string{"core/core.go": `package core

import (
	"errors"
	"fmt"
	"time"
)

var (
	ErrNotFound = errors.New("not found")
	ErrWrapped  = fmt.Errorf("wrap: %w", ErrNotFound)
	errHidden   = errors.New("hidden")
)

var ErrQuote = errors.New("say \"hi\"")

const (
	PageSize       = 10
	Greeting       = "hello"
	Timeout        = 5 * time.Second
	MaxUserID      = 7
	HTTPPort   int = 8080
	big            = 1
)

const Computed = PageSize * 2
`})
	want := strings.Join([]string{
		`errors ErrNotFound: { in: core, gen: false, message: "not found" }`,
		`errors ErrQuote: { in: core, gen: false, message: "say \"hi\"" }`,
		`consts greeting: { in: core, gen: false, type: string, value: "hello" }`,
		`consts http_port: { in: core, gen: false, type: int, value: 8080, go: { name: HTTPPort } }`,
		`consts max_user_id: { in: core, gen: false, type: int, value: 7 }`,
		`consts page_size: { in: core, gen: false, type: int, value: 10 }`,
		`consts timeout: { in: core, gen: false, type: duration, value: 5s }`,
	}, "\n")
	if got := lines(r); got != want {
		t.Fatalf("got\n%s\nwant\n%s", got, want)
	}
	skipped := map[string]bool{}
	for _, s := range r.Skipped {
		skipped[s.Name] = true
	}
	for _, n := range []string{"ErrWrapped", "Computed"} {
		if !skipped[n] {
			t.Errorf("%s가 옮기지 않은 목록에 없다: %+v", n, r.Skipped)
		}
	}
}

// 설계에 이미 있는 선언, 모듈 밖 패키지, 생성 파일, 테스트 파일은 보지 않는다.
func TestOutOfScope(t *testing.T) {
	r := draft(t, "errors:\n  ErrKnown: { in: core, gen: false, message: \"known\" }\n", map[string]string{
		"core/core.go":      "package core\n\nimport \"errors\"\n\nvar ErrKnown = errors.New(\"known\")\n",
		"core/core_test.go": "package core\n\nimport \"errors\"\n\nvar ErrTest = errors.New(\"t\")\n",
		"core/x.gen.go":     "// Code generated by daemok. DO NOT EDIT.\n\npackage core\n\nconst GenConst = 1\n",
		"other/other.go":    "package other\n\nconst Outside = 1\n",
	})
	if len(r.Nodes) != 0 {
		t.Fatalf("노드가 없어야 한다:\n%s", lines(r))
	}
}

// 초안을 설계 파일로 더하면 새 오류·경고 없이 통과한다.
func TestDraftPassesCheck(t *testing.T) {
	dir, root := project(t, "", map[string]string{"core/core.go": `package core

import "errors"

var ErrA = errors.New("a")

const Limit = 3
`})
	r, err := Draft(dir, root)
	if err != nil {
		t.Fatal(err)
	}
	if len(r.Nodes) != 2 {
		t.Fatalf("노드 2개여야 한다:\n%s", lines(r))
	}
	write(t, root, "design/l3.yaml", string(r.YAML))
	res := workspace.Check(dir, root)
	for _, d := range res.Diags {
		if d.Level != model.Info {
			t.Errorf("진단: %v", d)
		}
	}
	if res.Fatal {
		t.Fatalf("Fatal: %v", res.Diags)
	}
}

// 설계에 더하면 진단이 나는 노드는 빠지고 이유가 남는다. 다른 모듈에 같은 ID의 상수가 있으면 중복 ID다.
func TestValidateDropsBadNode(t *testing.T) {
	r := draft(t, "  other: { tier: a }\nconsts:\n  limit: { in: other, gen: false, value: 1 }\n", map[string]string{
		"core/core.go":   "package core\n\nconst Limit = 3\n\nconst Size = 4\n",
		"other/other.go": "package other\n\nconst Limit = 1\n",
	})
	if got := lines(r); got != "consts size: { in: core, gen: false, type: int, value: 4 }" {
		t.Fatalf("got\n%s", got)
	}
	var reason string
	for _, s := range r.Skipped {
		if s.Name == "Limit" {
			reason = s.Reason
		}
	}
	if !strings.Contains(reason, "중복 ID") {
		t.Fatalf("limit 이유: %q (%+v)", reason, r.Skipped)
	}
}

func TestSnakeID(t *testing.T) {
	for _, c := range []struct{ name, id, goName string }{
		{"PageSize", "page_size", ""},
		{"MaxUserID", "max_user_id", ""},
		{"HTTPPort", "http_port", "HTTPPort"},
		{"DefaultP2PPort", "default_p2p_port", "DefaultP2PPort"},
		{"Sha256Size", "sha256_size", ""},
		{"X", "x", ""},
	} {
		id, goName, ok := snakeID(c.name)
		if !ok || id != c.id || goName != c.goName {
			t.Errorf("%s: %q %q %v", c.name, id, goName, ok)
		}
	}
}

