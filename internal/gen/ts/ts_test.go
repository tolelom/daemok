package ts

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/tolelom/daemok/internal/model"
)

func load(t *testing.T, src string) *model.Model {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "d.yaml"), []byte("version: 0.5\ngo_module: example.com/x\ntiers: [a]\nmodules:\n  core: { tier: a }\n"+src), 0o644); err != nil {
		t.Fatal(err)
	}
	m, ds := model.Load(dir)
	if ds.HasErrors() {
		t.Fatalf("load:\n%v", ds)
	}
	return m
}

func TestGenerate(t *testing.T) {
	m := load(t, `ts_out: ../web/limits.gen.ts
consts:
  title_max:    { in: core, type: int, value: 255, export: [ts] }
  page_size:    { in: core, type: int, value: 10, export: [ts], summary: "한 페이지 기본 크기", gen: false }
  greeting:     { in: core, type: string, value: "a \"b\"", export: [ts] }
  internal_max: { in: core, type: int, value: 1 }
enums:
  post_status: { in: core, values: [published, draft], export: [ts] }
  user_id_kind: { in: core, values: [x], export: [ts] }
  hidden: { in: core, values: [y] }
`)
	got, ok := Generate(m)
	want := `// Code generated by daemok. DO NOT EDIT.

export const GREETING = "a \"b\"";

/** 한 페이지 기본 크기 */
export const PAGE_SIZE = 10;

export const TITLE_MAX = 255;

export const POST_STATUS = ["published", "draft"] as const;
export type PostStatus = (typeof POST_STATUS)[number];

export const USER_ID_KIND = ["x"] as const;
export type UserIDKind = (typeof USER_ID_KIND)[number];
`
	if !ok || string(got) != want {
		t.Fatalf("ok %v\n%s", ok, got)
	}
}

func TestGenerateNothing(t *testing.T) {
	for _, src := range []string{
		"consts:\n  a: { in: core, type: int, value: 1, export: [ts] }\n",
		"ts_out: web/x.gen.ts\nconsts:\n  a: { in: core, type: int, value: 1 }\n",
	} {
		if got, ok := Generate(load(t, src)); ok {
			t.Errorf("%q\n%s", src, got)
		}
	}
}

// 앞자리 0은 TS 모듈에서 문법 오류다. 설계 검사가 읽은 10진수 값으로 쓴다.
func TestGenerateDecimalValue(t *testing.T) {
	m := load(t, "ts_out: x.gen.ts\nconsts:\n  a: { in: core, type: int, value: 010, export: [ts] }\n  b: { in: core, type: int, value: +5, export: [ts] }\n")
	got, _ := Generate(m)
	for _, want := range []string{"export const A = 10;\n", "export const B = 5;\n"} {
		if !strings.Contains(string(got), want) {
			t.Errorf("%q가 없다:\n%s", want, got)
		}
	}
}

func TestGenerateTypes(t *testing.T) {
	m := load(t, `ts_out: x.gen.ts
enums:
  post_status: { in: core, values: [published, draft], export: [ts] }
types:
  user: { in: core, fields: { id: uint, name: string }, export: [ts] }
  post:
    in: core
    summary: 글
    export: [ts]
    gen: false
    fields:
      id: uint
      status: post_status
      tags: "[]string"
      author: { ref: user }
      reviewers: { ref: user, many: true }
      nick: { type: string, optional: true, summary: 별명 }
      raw: bytes
      meta: "map[string]any"
      by_id: "map[uint][]*user"
      created: time
      ok: bool
      extra: json.RawMessage
      opt_tags: { type: "[]string", optional: true }
      boss: { ref: user, optional: true }
      opt_meta: { type: "map[string]int", optional: true }
      opt_raw: { type: bytes, optional: true }
  hidden: { in: core, fields: { n: int } }
`)
	got, _ := Generate(m)
	want := `
export const POST_STATUS = ["published", "draft"] as const;
export type PostStatus = (typeof POST_STATUS)[number];

/** 글 */
export interface Post {
  id: number;
  status: PostStatus;
  tags: string[] | null;
  author: User | null;
  reviewers: User[] | null;
  /** 별명 */
  nick?: string;
  raw: string | null;
  meta: Record<string, unknown> | null;
  by_id: Record<string, (User | null)[] | null> | null;
  created: string;
  ok: boolean;
  extra: unknown;
  opt_tags?: string[];
  boss?: User;
  opt_meta?: Record<string, number> | null;
  opt_raw?: string;
}

export interface User {
  id: number;
  name: string;
}
`
	if !strings.HasSuffix(string(got), want) {
		t.Fatalf("got\n%s", got)
	}
}
