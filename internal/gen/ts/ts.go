// Package ts는 export: [ts]가 붙은 상수와 enum을 ts_out 파일 하나의 TypeScript로 만든다.
package ts

import (
	"encoding/json"
	"fmt"
	"slices"
	"sort"
	"strconv"
	"strings"

	"github.com/tolelom/daemok/internal/model"
)

// Header는 생성 헤더다. Go 생성 파일의 헤더와 같아야 한다(workspace 테스트가 확인).
const Header = "// Code generated by daemok. DO NOT EDIT."

// Generate는 ts_out에 쓸 내용을 준다. ts_out이 없거나 내보낼 것이 없으면 false다.
// gen: false는 Go 선언을 손으로 썼다는 뜻이라 TS에는 영향이 없다.
func Generate(m *model.Model) ([]byte, bool) {
	consts, enums := Exported(m)
	if m.TSOut == "" || len(consts)+len(enums) == 0 {
		return nil, false
	}
	var b strings.Builder
	b.WriteString(Header + "\n")
	for _, c := range consts {
		b.WriteString("\n" + doc(c.Summary))
		value := c.Value
		switch c.Type {
		case "int":
			if n, err := strconv.Atoi(c.Value); err == nil {
				value = strconv.Itoa(n) // 앞자리 0은 TS 모듈에서 문법 오류다
			}
		case "string":
			q, _ := json.Marshal(c.Value)
			value = string(q)
		}
		fmt.Fprintf(&b, "export const %s = %s;\n", ConstName(c.ID), value)
	}
	for _, e := range enums {
		vals := make([]string, len(e.Values))
		for i, v := range e.Values {
			q, _ := json.Marshal(v.Name)
			vals[i] = string(q)
		}
		b.WriteString("\n" + doc(e.Summary))
		fmt.Fprintf(&b, "export const %s = [%s] as const;\n", ConstName(e.ID), strings.Join(vals, ", "))
		fmt.Fprintf(&b, "export type %s = (typeof %s)[number];\n", TypeName(e.ID), ConstName(e.ID))
	}
	return []byte(b.String()), true
}

// Exported는 export에 ts가 있는 상수와 enum을 ID 순으로 준다.
func Exported(m *model.Model) ([]*model.Const, []*model.Enum) {
	var consts []*model.Const
	for _, c := range m.Consts {
		if slices.Contains(c.Export, "ts") {
			consts = append(consts, c)
		}
	}
	var enums []*model.Enum
	for _, e := range m.Enums {
		if slices.Contains(e.Export, "ts") {
			enums = append(enums, e)
		}
	}
	sort.Slice(consts, func(i, j int) bool { return consts[i].ID < consts[j].ID })
	sort.Slice(enums, func(i, j int) bool { return enums[i].ID < enums[j].ID })
	return consts, enums
}

// ConstName은 상수와 enum 값 목록의 TS 이름이다.
func ConstName(id string) string { return strings.ToUpper(id) }

// TypeName은 enum의 TS 타입 이름이다.
func TypeName(id string) string { return model.GoName(id) }

func doc(summary string) string {
	if summary == "" {
		return ""
	}
	return "/** " + strings.ReplaceAll(summary, "*/", "* /") + " */\n"
}
