// Package ts는 export: [ts]가 붙은 상수, enum, 타입을 ts_out 파일 하나의 TypeScript로 만든다.
package ts

import (
	"encoding/json"
	"fmt"
	"slices"
	"sort"
	"strconv"
	"strings"

	"github.com/tolelom/daemok/internal/model"
)

const Header = "// Code generated by daemok. DO NOT EDIT."

func Generate(m *model.Model) ([]byte, bool) {
	x := Exported(m)
	if m.TSOut == "" || x.Len() == 0 {
		return nil, false
	}
	var b strings.Builder
	b.WriteString(Header + "\n")
	for _, c := range x.Consts {
		b.WriteString("\n" + doc(c.Summary))
		value := c.Value
		switch c.Type {
		case "int":
			if n, err := strconv.Atoi(c.Value); err == nil {
				value = strconv.Itoa(n)
			}
		case "string":
			q, _ := json.Marshal(c.Value)
			value = string(q)
		}
		fmt.Fprintf(&b, "export const %s = %s;\n", ConstName(c.ID), value)
	}
	for _, e := range x.Enums {
		vals := make([]string, len(e.Values))
		for i, v := range e.Values {
			q, _ := json.Marshal(v.Name)
			vals[i] = string(q)
		}
		b.WriteString("\n" + doc(e.Summary))
		fmt.Fprintf(&b, "export const %s = [%s] as const;\n", ConstName(e.ID), strings.Join(vals, ", "))
		fmt.Fprintf(&b, "export type %s = (typeof %s)[number];\n", TypeName(e.ID), ConstName(e.ID))
	}
	for _, t := range x.Types {
		b.WriteString("\n" + doc(t.Summary))
		fmt.Fprintf(&b, "export interface %s {\n", TypeName(t.ID))
		for _, f := range t.Fields {
			ft, optional, _ := FieldType(m, f)
			key := f.Name
			if optional {
				key += "?"
			}
			if f.Summary != "" {
				b.WriteString("  " + doc(f.Summary))
			}
			fmt.Fprintf(&b, "  %s: %s;\n", key, ft)
		}
		b.WriteString("}\n")
	}
	return []byte(b.String()), true
}

type Nodes struct {
	Consts []*model.Const
	Enums  []*model.Enum
	Types  []*model.Type
}

func (x Nodes) Len() int { return len(x.Consts) + len(x.Enums) + len(x.Types) }

func Exported(m *model.Model) Nodes {
	var x Nodes
	for _, c := range m.Consts {
		if slices.Contains(c.Export, "ts") {
			x.Consts = append(x.Consts, c)
		}
	}
	for _, e := range m.Enums {
		if slices.Contains(e.Export, "ts") {
			x.Enums = append(x.Enums, e)
		}
	}
	for _, t := range m.Types {
		if slices.Contains(t.Export, "ts") {
			x.Types = append(x.Types, t)
		}
	}
	sort.Slice(x.Consts, func(i, j int) bool { return x.Consts[i].ID < x.Consts[j].ID })
	sort.Slice(x.Enums, func(i, j int) bool { return x.Enums[i].ID < x.Enums[j].ID })
	sort.Slice(x.Types, func(i, j int) bool { return x.Types[i].ID < x.Types[j].ID })
	return x
}

func ConstName(id string) string { return strings.ToUpper(id) }

func TypeName(id string) string { return model.GoName(id) }

func doc(summary string) string {
	if summary == "" {
		return ""
	}
	return "/** " + strings.ReplaceAll(summary, "*/", "* /") + " */\n"
}
