package golang

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"path"
	"sort"
	"strings"
)

const Header = "// Code generated by daemok. DO NOT EDIT."

func IsDaemokGenerated(src []byte) bool {
	line, _, _ := bytes.Cut(src, []byte("\n"))
	return string(bytes.TrimSuffix(line, []byte("\r"))) == Header
}

func IsDaemokGeneratedFile(f *ast.File) bool {
	if len(f.Comments) == 0 {
		return false
	}
	c := f.Comments[0].List[0]
	return c.Pos() == f.FileStart && IsDaemokGenerated([]byte(c.Text))
}

type File struct {
	Path    string
	Content []byte
}

type goFile struct {
	path    string
	pkg     string
	imports map[string]string
	parts   []string
	shape   bool
}

func (f *goFile) use(importPath string) string {
	if f.shape {
		return path.Base(importPath)
	}
	if name, ok := f.imports[importPath]; ok {
		return name
	}
	name := path.Base(importPath)
	if f.nameTaken(name) {
		if parent := path.Base(path.Dir(importPath)); parent != "." && parent != "/" {
			name = parent + name
		} else {
			name += "pkg"
		}
		for i := 2; f.nameTaken(name); i++ {
			name = fmt.Sprintf("%s%d", path.Base(importPath), i)
		}
	}
	f.imports[importPath] = name
	return name
}

func (f *goFile) blank(importPath string) {
	f.imports[importPath] = "_"
}

var localNames = map[string]bool{
	"m": true, "d": true, "v": true, "ok": true, "err": true, "s": true, "t": true, "c": true,
	"i": true, "x": true, "out": true, "key": true, "ev": true, "fail": true, "undo": true, "got": true, "cases": true,
}

func (f *goFile) nameTaken(name string) bool {
	if name == f.pkg || localNames[name] {
		return true
	}
	for _, n := range f.imports {
		if n == name {
			return true
		}
	}
	return false
}

func (f *goFile) add(format string, args ...any) {
	f.parts = append(f.parts, fmt.Sprintf(format, args...))
}

func (f *goFile) render() (File, error) {
	var b strings.Builder
	b.WriteString(Header + "\n\npackage " + f.pkg + "\n")
	if len(f.imports) > 0 {
		var std, other []string
		for p := range f.imports {
			if first, _, _ := strings.Cut(p, "/"); strings.Contains(first, ".") {
				other = append(other, p)
			} else {
				std = append(std, p)
			}
		}
		sort.Strings(std)
		sort.Strings(other)
		b.WriteString("\nimport (\n")
		for i, group := range [][]string{std, other} {
			if i == 1 && len(std) > 0 && len(other) > 0 {
				b.WriteString("\n")
			}
			for _, p := range group {
				name := f.imports[p]
				if name == path.Base(p) {
					fmt.Fprintf(&b, "\t%q\n", p)
				} else {
					fmt.Fprintf(&b, "\t%s %q\n", name, p)
				}
			}
		}
		b.WriteString(")\n")
	}
	for _, p := range f.parts {
		b.WriteString("\n" + p + "\n")
	}
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return File{}, fmt.Errorf("생성 코드를 포맷할 수 없다: %s: %v", f.path, err)
	}
	return File{Path: f.path, Content: out}, nil
}
