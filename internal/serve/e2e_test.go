// 분석 모드 지도에서 많은 관계선, 긴 이름, 디렉토리 영역 띠, 공용 띠를, 모듈 탭에서 영역 목록과 하위 패키지·외부 의존·L3 후보를 본다. DAEMOK_E2E=1일 때만 돈다.
func TestUIMapDenseE2E(t *testing.T) {
	if os.Getenv("DAEMOK_E2E") != "1" {
		t.Skip("DAEMOK_E2E=1일 때만 돈다")
	}
	node, err := exec.LookPath("node")
	if err != nil {
		t.Skip("node가 없다")
	}
	root := t.TempDir()
	write := func(rel, src string) {
		os.MkdirAll(filepath.Join(root, filepath.Dir(rel)), 0o755)
		os.WriteFile(filepath.Join(root, rel), []byte(src), 0o644)
	}
	write("library/base/x.go", "package base\n")
	write("go.mod", "module example.com/d\n\nrequire example.org/ext v1.0.0\n")
	write("box/core/reg/errs.go", "package reg\n\nimport (\n\t\"errors\"\n\t_ \"example.org/ext/sub\"\n)\n\nvar (\n\tErrGone = errors.New(\"gone\")\n\tErrBusy = errors.New(\"busy\")\n)\n")
	var leaves []string
	for i := 0; i < 13; i++ {
		p := "leaf" + string(rune('a'+i))
		write("library/thirdparty/"+p+"/x.go", "package "+p+"\nimport _ \"example.com/d/library/base\"\n")
		leaves = append(leaves, `_ "example.com/d/library/thirdparty/`+p+`"`)
	}
	imp := "import (\n" + strings.Join(leaves, "\n") + "\n)\n"
	for _, p := range []string{"reg", "reg/query", "reg/service", "shop", "shop/query", "shop/rulecheckevaluation/service"} {
		write("box/core/"+p+"/x.go", "package "+filepath.Base(p)+"\n"+imp)
	}
	// 같은 줄 관계선: shop → reg는 이웃 칸, worker → shop은 reg를 건너는 칸이다. reg → shop은 반대 방향이다.
	// 지도 부제: 한글 긴 패키지 설명이 상자를 넘지 않는지 본다.
	write("box/core/shop/doc.go", "// Package shop은 매장 상품과 가격과 진열과 재고를 함께 다루는 아주 긴 설명이다.\npackage shop\n")
	write("box/core/shop/up.go", "package shop\nimport \"example.com/d/box/core/reg\"\nvar _ = reg.ErrGone\n")
	// 모듈 탭 연결 표: shop/query가 reg/service의 이름을 별칭 import로 쓴다.
	write("box/core/reg/service/api.go", "package service\n\ntype Service struct{}\n\nfunc Find() {}\n")
	write("box/core/shop/query/use.go", "package query\nimport rs \"example.com/d/box/core/reg/service\"\nvar _ = rs.Find\nvar _ rs.Service\n")
	write("box/core/reg/svc.go", "package reg\nimport _ \"example.com/d/box/core/shop/query\"\n")
	write("box/core/inventory_reconciliation_worker/x.go", "package worker\n"+imp+"import _ \"example.com/d/box/core/shop\"\n")
	write("box/main.go", "package box\nimport _ \"example.com/d/box/core/reg\"\n")
	s := New(filepath.Join(root, "design"), root)
	s.Poll()
	local(t, s)
	srv := httptest.NewServer(s.Handler())
	defer srv.Close()
	out, err := exec.Command(node, filepath.Join("..", "..", "scripts", "e2e", "mapdense.mjs"), srv.URL+"/").CombinedOutput()
	if err != nil {
		t.Fatalf("%v\n%s", err, out)
	}
}

