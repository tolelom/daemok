func TestDeclaredButUnreferenced(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"design/d.yaml": `version: 0.5
go_module: example.com/u
tiers: [a, b]
modules:
  events: { tier: a }
  pub:    { tier: b, depends_on: [events] }
  sub:    { tier: b, depends_on: [events] }
enums:
  event_type: { in: events, go: { type: EventType, prefix: Event }, values: [done] }
event_kinds:
  ev: { in: events, key: event_type, subscribers: [sub] }
events:
  done: { kind: ev, publishers: [pub] }
`,
		"events/events.go": "package events\n",
		"pub/pub.go":       "package pub\n\nimport _ \"example.com/u/events\"\n",
		"sub/sub.go":       "package sub\n\nimport _ \"example.com/u/events\"\n",
	}
	for p, c := range files {
		writeFile(t, filepath.Join(root, p), c)
	}
	m, ds := model.Load(filepath.Join(root, "design"))
	if ds.HasErrors() {
		t.Fatal(ds)
	}
	var msgs []string
	for _, d := range Scan(m, root) {
		msgs = append(msgs, d.Msg)
	}
	joined := strings.Join(msgs, "\n")
	for _, want := range []string{
		"이벤트 상수를 쓰지 않는다: 모듈 pub, 이벤트 done (EventDone)",
		"이벤트 목록 함수를 쓰지 않는다: 모듈 sub, 이벤트 종류 ev (EventTypeValues)",
	} {
		if !strings.Contains(joined, want) {
			t.Errorf("%q 없음:\n%s", want, joined)
		}
	}
}

func writeFile(t *testing.T, p, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestDotImportBuildIgnoreAndGeneratedFiles(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"design/d.yaml": `version: 0.5
go_module: example.com/u
tiers: [a, b]
modules:
  events: { tier: a }
  dot:    { tier: b, depends_on: [events] }
  self:   { tier: b }
  tagged: { tier: b }
enums:
  event_type: { in: events, go: { type: EventType, prefix: Event }, values: [done] }
event_kinds:
  ev: { in: events, key: event_type }
events:
  done: { kind: ev, publishers: [dot, events] }
`,
		"events/event_type.gen.go": "// Code generated by daemok. DO NOT EDIT.\n\npackage events\n\ntype EventType string\n\nconst EventDone EventType = \"done\"\n",
		"dot/dot.go":               "package dot\n\nimport . \"example.com/u/events\"\n\nvar x = EventDone\n",
		"self/self.go":             "package self\n",
		"tagged/t.go":              "//go:build ignore\n\npackage tagged\n\nimport _ \"example.com/u/events\"\n",
		"tagged/linux.go":          "//go:build !windows && linux\n\npackage tagged\n\nimport _ \"example.com/u/dot\"\n",
	}
	for p, c := range files {
		writeFile(t, filepath.Join(root, p), c)
	}
	m, ds := model.Load(filepath.Join(root, "design"))
	if ds.HasErrors() {
		t.Fatal(ds)
	}
	var msgs []string
	for _, d := range Scan(m, root) {
		msgs = append(msgs, d.Level.String()+": "+d.Msg)
	}
	joined := strings.Join(msgs, "\n")
	if strings.Contains(joined, "모듈 dot") {
		t.Errorf("도트 import 참조를 세지 않았다:\n%s", joined)
	}
	if !strings.Contains(joined, "이벤트 상수를 쓰지 않는다: 모듈 events") {
		t.Errorf("생성 파일의 선언을 참조로 셌다:\n%s", joined)
	}
	if strings.Contains(joined, "tagged → events") {
		t.Errorf("ignore 파일을 읽었다:\n%s", joined)
	}
	if !strings.Contains(joined, "설계에 없는 의존을 import한다: tagged → dot") {
		t.Errorf("OS 조건 파일은 읽어야 한다:\n%s", joined)
	}
}

