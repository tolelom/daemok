// Package codescan은 코드의 import와 이벤트 상수 참조를 설계와 대조한다.
package codescan

import (
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strconv"
	"strings"

	"github.com/tolelom/daemok/internal/gosrc"
	"github.com/tolelom/daemok/internal/model"
	"github.com/tolelom/daemok/internal/yaml"
)

type scanner struct {
	m     *model.Model
	root  string
	fset  *token.FileSet
	diags model.Diagnostics
	units map[string]string // import 경로 → 모듈·멤버 ID
	// 모듈·멤버 ID → 그 패키지가 import한 설계 단위
	imports map[string]map[string]bool
	// 모듈·멤버 ID → 쓴 이벤트 상수와 목록 함수의 이름
	refs map[string]map[string]bool
	// 모듈·멤버 ID → 패키지 최상위 선언 이름
	decls map[string]map[string]bool
	// 모듈·멤버 ID → 타입 이름 → 선언과 그 파일
	typeSpecs map[string]map[string]typeSpec
}

// unit은 코드 디렉토리를 가진 모듈이나 그룹 멤버다.
type unit struct {
	id, dir string
}

// Scan은 설계 검사를 통과한 모델의 모듈·멤버 코드를 읽어 진단을 준다.
func Scan(m *model.Model, root string) model.Diagnostics {
	s := &scanner{
		m: m, root: root, fset: token.NewFileSet(),
		units: map[string]string{}, imports: map[string]map[string]bool{}, refs: map[string]map[string]bool{},
		decls: map[string]map[string]bool{}, typeSpecs: map[string]map[string]typeSpec{},
	}
	us := s.unitList()
	for _, u := range us {
		s.units[m.GoModule+"/"+u.dir] = u.id
	}
	for _, u := range us {
		s.scanUnit(u)
	}
	s.queryPackages()
	s.unusedDeps(us)
	s.eventRefs(us)
	s.handWritten()
	s.shapes()
	s.diags.Sort()
	return s.diags
}

func (s *scanner) unitList() []unit {
	var out []unit
	for _, mod := range s.m.Modules {
		out = append(out, unit{mod.ID, mod.Path})
	}
	for _, g := range s.m.Groups {
		for _, mem := range g.Members {
			out = append(out, unit{mem.ID, mem.Path()})
		}
	}
	return out
}

// goFiles는 모듈·멤버 디렉토리의 Go 파일이다. 파일 선택은 gosrc.Files를 따른다.
func (s *scanner) goFiles(dir string) []*ast.File {
	files, errs := gosrc.Files(s.fset, filepath.Join(s.root, filepath.FromSlash(dir)), parser.SkipObjectResolution)
	for _, e := range errs {
		s.diags.Errorf(yaml.Pos{File: e.Path}, "Go 파일을 읽을 수 없다: %v", e.Err)
	}
	return files
}

// generated는 첫 줄이 daemok 생성 헤더인 파일인지다.
func generated(f *ast.File) bool {
	return len(f.Comments) > 0 && f.Comments[0].List[0].Text == "// Code generated by daemok. DO NOT EDIT." && f.Comments[0].Pos() < f.Package
}

func (s *scanner) pos(p token.Pos) yaml.Pos {
	q := s.fset.Position(p)
	return yaml.Pos{File: q.Filename, Line: q.Line, Col: q.Column}
}

func (s *scanner) scanUnit(u unit) {
	s.imports[u.id] = map[string]bool{}
	s.refs[u.id] = map[string]bool{}
	s.decls[u.id] = map[string]bool{}
	s.typeSpecs[u.id] = map[string]typeSpec{}
	unmanaged := map[string]bool{}
	for _, f := range s.goFiles(u.dir) {
		for _, name := range gosrc.TopNames(f) {
			s.decls[u.id][name] = true
		}
		collectTypeSpecs(f, s.typeSpecs[u.id])
		for _, im := range f.Imports {
			ip, _ := strconv.Unquote(im.Path.Value)
			if ip != s.m.GoModule && !strings.HasPrefix(ip, s.m.GoModule+"/") {
				continue
			}
			target, ok := s.units[ip]
			if !ok {
				if !unmanaged[ip] {
					unmanaged[ip] = true
					s.diags.Infof(s.pos(im.Pos()), "관리하지 않는 패키지를 import한다: %s → %s", u.id, ip)
				}
				continue
			}
			if target == u.id {
				continue
			}
			s.imports[u.id][target] = true
			if s.m.CanDepend(u.id, target) {
				continue
			}
			if s.receivesFrom(u.id, target) {
				s.diags.Errorf(s.pos(im.Pos()), "needs로만 이어진 모듈을 직접 import한다: %s → %s", u.id, target)
			} else {
				s.diags.Errorf(s.pos(im.Pos()), "설계에 없는 의존을 import한다: %s → %s", u.id, target)
			}
		}
		if !generated(f) {
			s.collectRefs(u.id, f)
			s.adHocErrors(u.id, f)
			s.enumLiterals(u.id, f)
		}
	}
}

// needsOf는 id가 받는 계약이다. 멤버는 그룹의 needs도 받는다.
func (s *scanner) needsOf(id string) []model.Need {
	if mem := s.m.Member(id); mem != nil {
		return append(slices.Clone(mem.Group.Needs), mem.Needs...)
	}
	if mod := s.m.Module(id); mod != nil {
		return mod.Needs
	}
	return nil
}

// receivesFrom은 id가 target 모듈의 계약을 needs로 받는지다.
func (s *scanner) receivesFrom(id, target string) bool {
	for _, n := range s.needsOf(id) {
		if ct := s.m.Contract(n.Contract.Name); ct != nil && ct.In.Name == target {
			return true
		}
	}
	return false
}

// queryPackages는 query 계약을 가진 모듈의 query 패키지가 data 모듈 말고 다른 설계 모듈을 import하는지 본다.
func (s *scanner) queryPackages() {
	done := map[string]bool{}
	for _, ct := range s.m.Contracts {
		if ct.Kind != "query" || done[ct.In.Name] {
			continue
		}
		done[ct.In.Name] = true
		o, ok := s.m.Owner(ct.In.Name)
		if !ok {
			continue
		}
		dir := o.Path + "/query"
		for _, f := range s.goFiles(dir) {
			for _, im := range f.Imports {
				ip, _ := strconv.Unquote(im.Path.Value)
				target, ok := s.units[ip]
				if !ok {
					continue
				}
				if mod := s.m.Module(target); mod == nil || mod.Role != "data" {
					s.diags.Errorf(s.pos(im.Pos()), "query 패키지가 data가 아닌 모듈을 import한다: %s → %s", dir, target)
				}
			}
		}
	}
}

// unusedDeps는 모듈의 depends_on 대상을 import하지 않으면 정보로 알린다. 그룹 대상은 멤버 하나를 import하면 된다.
// 코드 디렉토리가 없는 모듈은 보지 않는다.
func (s *scanner) unusedDeps(us []unit) {
	for _, mod := range s.m.Modules {
		if !s.dirExists(mod.Path) {
			continue
		}
		for _, d := range mod.DependsOn {
			targets := []string{d.Name}
			if g := s.m.Group(d.Name); g != nil {
				targets = nil
				for _, mem := range g.Members {
					targets = append(targets, mem.ID)
				}
			}
			used := false
			for _, t := range targets {
				used = used || s.imports[mod.ID][t]
			}
			if !used {
				s.diags.Infof(d.Pos, "설계상 의존하지만 import하지 않는다: %s → %s", mod.ID, d.Name)
			}
		}
	}
}

func (s *scanner) dirExists(dir string) bool {
	st, err := os.Stat(filepath.Join(s.root, filepath.FromSlash(dir)))
	return err == nil && st.IsDir()
}

// collectRefs는 이벤트 종류 모듈의 이름을 쓴 식별자를 모은다.
// 다른 패키지에서는 import 이름(별칭 포함)의 선택자, 이벤트 종류 모듈 안에서는 맨 식별자다.
func (s *scanner) collectRefs(id string, f *ast.File) {
	kindImports := map[string]bool{} // 이 파일에서 이벤트 종류 모듈을 가리키는 이름
	inKindModule := false            // 이벤트 종류 모듈 안이거나 그 모듈을 도트 import하면 맨 식별자를 센다
	for _, ek := range s.m.EventKinds {
		ip := s.m.ImportPath(ek.In.Name)
		if ek.In.Name == id {
			inKindModule = true
		}
		for _, im := range f.Imports {
			if p, _ := strconv.Unquote(im.Path.Value); p == ip {
				name := filepath.Base(ip)
				if im.Name != nil {
					name = im.Name.Name
				}
				if name == "." {
					inKindModule = true
				}
				kindImports[name] = true
			}
		}
	}
	ast.Inspect(f, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.SelectorExpr:
			if pkg, ok := x.X.(*ast.Ident); ok && kindImports[pkg.Name] {
				s.refs[id][x.Sel.Name] = true
			}
		case *ast.Ident:
			if inKindModule {
				s.refs[id][x.Name] = true
			}
		}
		return true
	})
}

// eventRefs는 발행자·구독자가 이벤트 상수를 쓰는지, 적히지 않은 모듈이 쓰는지 본다.
func (s *scanner) eventRefs(us []unit) {
	m := s.m
	for _, ek := range m.EventKinds {
		en := m.Enum(ek.Key.Name)
		if en == nil {
			continue
		}
		declared := map[string]bool{}
		for _, r := range ek.Subscribers {
			declared[r.Name] = true
			if s.dirExists(s.ownerDir(r.Name)) && !s.refs[r.Name][en.GoType()+"Values"] {
				s.diags.Errorf(r.Pos, "이벤트 목록 함수를 쓰지 않는다: 모듈 %s, 이벤트 종류 %s (%sValues)", r.Name, ek.ID, en.GoType())
			}
		}
		for _, v := range en.Values {
			e := m.Event(v.Name)
			if e == nil {
				continue
			}
			constName := en.ConstName(v.Name)
			users := map[string]bool{}
			for _, r := range append(slices.Clone(e.Publishers), e.Subscribers...) {
				users[r.Name] = true
				if s.dirExists(s.ownerDir(r.Name)) && !s.refs[r.Name][constName] {
					s.diags.Errorf(r.Pos, "이벤트 상수를 쓰지 않는다: 모듈 %s, 이벤트 %s (%s)", r.Name, e.ID, constName)
				}
			}
			var extra []string
			for _, u := range us {
				if u.id != ek.In.Name && !users[u.id] && !declared[u.id] && s.refs[u.id][constName] {
					extra = append(extra, u.id)
				}
			}
			sort.Strings(extra)
			for _, id := range extra {
				s.diags.Warnf(e.Pos, "발행자나 구독자로 적히지 않은 모듈이 이벤트를 쓴다: 모듈 %s, 이벤트 %s", id, e.ID)
			}
		}
	}
}

// handWritten은 gen: false 노드가 생성 코드 대신 둔다고 한 선언이 소유 모듈 패키지에 있는지 본다.
// 손으로 쓴 코드에 생성 코드와 같은 이름이 있다고 볼 수 있는 노드만 본다. 이벤트 종류, 흐름, 함수는 보지 않는다.
// enum은 타입과 값 상수만 보고 목록 함수는 보지 않는다. 코드 디렉토리가 없는 모듈은 보지 않는다.
func (s *scanner) handWritten() {
	m := s.m
	need := func(o model.Owned, what string, names ...string) {
		if o.Gen || !s.dirExists(s.ownerDir(o.In.Name)) {
			return
		}
		for _, n := range names {
			if !s.decls[o.In.Name][n] {
				s.diags.Errorf(o.Pos, "손으로 쓴다고 한 선언이 코드에 없다: 모듈 %s, %s %s (%s)", o.In.Name, what, o.ID, n)
			}
		}
	}
	for _, e := range m.Enums {
		names := []string{e.GoType()}
		for _, v := range e.Values {
			names = append(names, e.ConstName(v.Name))
		}
		need(e.Owned, "enum", names...)
	}
	for _, k := range m.Consts {
		need(k.Owned, "상수", k.GoName())
	}
	for _, e := range m.Errors {
		need(e.Owned, "에러", e.GoName())
	}
	for _, t := range m.Types {
		need(t.Owned, "타입", t.GoName())
	}
	for _, ct := range m.Contracts {
		if ct.Kind == "call" {
			need(ct.Owned, "계약", ct.GoName())
		}
	}
	for _, hk := range m.HandlerKinds {
		need(hk.Owned, "핸들러 종류", hk.GoName())
	}
}

func (s *scanner) ownerDir(id string) string {
	o, _ := s.m.Owner(id)
	return o.Path
}

// adHocErrors는 쓸 수 있는 설계 에러가 있는 모듈의 함수 본문에서 errors.New를 부르면 정보로 알린다.
// 상황마다 메시지가 다른 정당한 경우가 섞여 있어 경고(--strict 실패)로 두지 않는다.
// 패키지 수준 var 선언(설계 에러를 손으로 둔 gen: false 선언)과 fmt.Errorf의 감싸기는 보지 않는다.
func (s *scanner) adHocErrors(id string, f *ast.File) {
	visible := false
	for _, e := range s.m.Errors {
		if e.In.Name == id || s.m.CanDepend(id, e.In.Name) {
			visible = true
			break
		}
	}
	if !visible {
		return
	}
	name := ""
	for _, im := range f.Imports {
		if p, _ := strconv.Unquote(im.Path.Value); p == "errors" {
			name = "errors"
			if im.Name != nil {
				name = im.Name.Name
			}
		}
	}
	if name == "" || name == "_" || name == "." {
		return
	}
	for _, d := range f.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || fn.Body == nil {
			continue
		}
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			if sel, ok := call.Fun.(*ast.SelectorExpr); ok && sel.Sel.Name == "New" {
				if pkg, ok := sel.X.(*ast.Ident); ok && pkg.Name == name {
					s.diags.Infof(s.pos(call.Pos()), "설계 에러가 있는데 즉석 errors.New를 쓴다: 모듈 %s", id)
				}
			}
			return true
		})
	}
}

// enumLiterals는 쓸 수 있는 설계 enum의 값과 같은 문자열 리터럴을 함수 본문의 비교(==, !=),
// switch case, SQL 메서드의 자리표시자 값(placeholderArgs)에서 쓰면 정보로 알린다. enum 상수를 쓰면 값이 바뀔 때 컴파일러가 잡는다.
// 로그 키나 외부 프로토콜 문자열처럼 다른 자리의 같은 문자열은 enum과 상관없을 때가 많아 보지 않는다.
func (s *scanner) enumLiterals(id string, f *ast.File) {
	consts := map[string]string{} // 값 → 상수 이름
	for _, en := range s.m.Enums {
		if en.In.Name != id && !s.m.CanDepend(id, en.In.Name) {
			continue
		}
		for _, v := range en.Values {
			if _, dup := consts[v.Name]; !dup {
				consts[v.Name] = en.ConstName(v.Name)
			}
		}
	}
	if len(consts) == 0 {
		return
	}
	for _, d := range f.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || fn.Body == nil {
			continue
		}
		var compared []ast.Expr
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			switch x := n.(type) {
			case *ast.BinaryExpr:
				if x.Op == token.EQL || x.Op == token.NEQ {
					compared = append(compared, x.X, x.Y)
				}
			case *ast.CaseClause:
				compared = append(compared, x.List...)
			case *ast.CallExpr:
				compared = append(compared, placeholderArgs(x)...)
			}
			return true
		})
		for _, e := range compared {
			lit, ok := ast.Unparen(e).(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				continue
			}
			v, err := strconv.Unquote(lit.Value)
			if c, hit := consts[v]; err == nil && hit {
				s.diags.Infof(s.pos(lit.Pos()), "enum 상수 대신 문자열 리터럴을 쓴다: 모듈 %s, %q (%s)", id, v, c)
			}
		}
	}
}

// sqlMethods는 쿼리 문자열과 자리표시자 값을 함께 받는 GORM·database/sql 메서드다.
var sqlMethods = map[string]bool{
	"Where": true, "Or": true, "Not": true, "Having": true, "Joins": true, "Raw": true, "Exec": true,
	"Find": true, "First": true, "Take": true, "Last": true, "Delete": true,
	"Query": true, "QueryRow": true, "QueryContext": true, "QueryRowContext": true, "ExecContext": true,
}

// placeholderArgs는 SQL 메서드 호출에서 ?가 든 문자열 리터럴 인자 뒤의 인자다.
// db.Where("status = ?", "published")의 값 자리다. IN ?에 넘긴 슬라이스 리터럴은 원소를 준다.
func placeholderArgs(call *ast.CallExpr) []ast.Expr {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok || !sqlMethods[sel.Sel.Name] {
		return nil
	}
	for i, a := range call.Args {
		lit, ok := ast.Unparen(a).(*ast.BasicLit)
		if !ok || lit.Kind != token.STRING {
			continue
		}
		q, err := strconv.Unquote(lit.Value)
		if err != nil || !strings.Contains(q, "?") {
			continue
		}
		var out []ast.Expr
		for _, v := range call.Args[i+1:] {
			if cl, ok := ast.Unparen(v).(*ast.CompositeLit); ok {
				out = append(out, cl.Elts...)
			} else {
				out = append(out, v)
			}
		}
		return out
	}
	return nil
}
