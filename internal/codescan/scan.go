// Package codescan은 코드의 import와 이벤트 상수 참조를 설계와 대조한다.
package codescan

import (
	"go/ast"
	"go/parser"
	"go/token"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/tolelom/daemok/internal/gosrc"
	"github.com/tolelom/daemok/internal/model"
	"github.com/tolelom/daemok/internal/yaml"
)

type scanner struct {
	m     *model.Model
	root  string
	fset  *token.FileSet
	diags model.Diagnostics
	units map[string]string // import 경로 → 모듈·멤버 ID
	// 모듈·멤버 ID → 그 패키지가 import한 설계 단위
	imports map[string]map[string]bool
	// 모듈·멤버 ID → 쓴 이벤트 상수와 목록 함수의 이름
	refs map[string]map[string]bool
	// 모듈·멤버 ID → 패키지 최상위 선언 이름
	decls map[string]map[string]bool
	// 모듈·멤버 ID → 타입 이름 → 선언과 그 파일
	typeSpecs map[string]map[string]typeSpec
	// 즉석 errors.New 호출. 모두 모은 뒤 같은 메시지 수를 붙여 알린다.
	adHoc []adHocCall
}

// unit은 코드 디렉토리를 가진 모듈이나 그룹 멤버다.
type unit struct {
	id, dir string
}

// Scan은 설계 검사를 통과한 모델의 모듈·멤버 코드를 읽어 진단을 준다.
func Scan(m *model.Model, root string) model.Diagnostics {
	s := &scanner{
		m: m, root: root, fset: token.NewFileSet(),
		units: map[string]string{}, imports: map[string]map[string]bool{}, refs: map[string]map[string]bool{},
		decls: map[string]map[string]bool{}, typeSpecs: map[string]map[string]typeSpec{},
	}
	us := s.unitList()
	for _, u := range us {
		s.units[m.GoModule+"/"+u.dir] = u.id
	}
	for _, u := range us {
		s.scanUnit(u)
	}
	s.reportAdHoc()
	s.queryPackages()
	s.unusedDeps(us)
	s.eventRefs(us)
	s.handWritten()
	s.shapes()
	s.diags.Sort()
	return s.diags
}

func (s *scanner) unitList() []unit {
	var out []unit
	for _, mod := range s.m.Modules {
		out = append(out, unit{mod.ID, mod.Path})
	}
	for _, g := range s.m.Groups {
		for _, mem := range g.Members {
			out = append(out, unit{mem.ID, mem.Path()})
		}
	}
	return out
}

// goFiles는 모듈·멤버 디렉토리의 Go 파일이다. 파일 선택은 gosrc.Files를 따른다.
func (s *scanner) goFiles(dir string) []*ast.File {
	files, errs := gosrc.Files(s.fset, filepath.Join(s.root, filepath.FromSlash(dir)), parser.SkipObjectResolution)
	for _, e := range errs {
		s.diags.Errorf(yaml.Pos{File: e.Path}, "Go 파일을 읽을 수 없다: %v", e.Err)
	}
	return files
}

// generated는 첫 줄이 daemok 생성 헤더인 파일인지다.
func generated(f *ast.File) bool {
	return len(f.Comments) > 0 && f.Comments[0].List[0].Text == "// Code generated by daemok. DO NOT EDIT." && f.Comments[0].Pos() < f.Package
}

func (s *scanner) pos(p token.Pos) yaml.Pos {
	q := s.fset.Position(p)
	return yaml.Pos{File: q.Filename, Line: q.Line, Col: q.Column}
}

func (s *scanner) scanUnit(u unit) {
	s.imports[u.id] = map[string]bool{}
	s.refs[u.id] = map[string]bool{}
	s.decls[u.id] = map[string]bool{}
	s.typeSpecs[u.id] = map[string]typeSpec{}
	unmanaged := map[string]bool{}
	for _, f := range s.goFiles(u.dir) {
		for _, name := range gosrc.TopNames(f) {
			s.decls[u.id][name] = true
		}
		collectTypeSpecs(f, s.typeSpecs[u.id])
		for _, im := range f.Imports {
			ip, _ := strconv.Unquote(im.Path.Value)
			if ip != s.m.GoModule && !strings.HasPrefix(ip, s.m.GoModule+"/") {
				continue
			}
			target, ok := s.units[ip]
			if !ok {
				if !unmanaged[ip] {
					unmanaged[ip] = true
					s.diags.Infof(s.pos(im.Pos()), "관리하지 않는 패키지를 import한다: %s → %s", u.id, ip)
				}
				continue
			}
			if target == u.id {
				continue
			}
			s.imports[u.id][target] = true
			if s.m.CanDepend(u.id, target) {
				continue
			}
			if s.receivesFrom(u.id, target) {
				s.diags.Errorf(s.pos(im.Pos()), "needs로만 이어진 모듈을 직접 import한다: %s → %s", u.id, target)
			} else {
				s.diags.Errorf(s.pos(im.Pos()), "설계에 없는 의존을 import한다: %s → %s", u.id, target)
			}
		}
		if !generated(f) {
			s.collectRefs(u.id, f)
			s.adHocErrors(u.id, f)
			s.enumLiterals(u.id, f)
		}
	}
}
